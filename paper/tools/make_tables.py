def holm_adjust(ps):
    """Holm step-down adjustment of a list of raw p-values (order preserved)."""
    order = sorted(range(len(ps)), key=lambda i: ps[i])
    adj, run = [0.0] * len(ps), 0.0
    for rank, i in enumerate(order):
        run = max(run, min(1.0, (len(ps) - rank) * ps[i]))
        adj[i] = run
    return adj


def revision_family():
    """Raw block/segment p of the comparisons added in revision (+ rel. GBDTs and EULER, four settings) and their
    Holm adjustment as a second family, separate from the pre-specified family of the four original baselines."""
    rows = []
    for key, *_ in E.SETTINGS:
        for name, _ in MATCHED:
            c = (rev(key, "rev2", "posthoc/posthoc.json") or {}).get("comparisons", {}).get(name)
            if c:
                rows.append(((key, name), c["all_rows_block"]["p_randomisation_two_sided"]["macro_mcc"],
                             c["all_rows_segment"]["p_randomisation_two_sided"]["macro_mcc"]))
        e = E.binary_comparison(key)
        rows.append(((key, "EULER"), e["p_block"], e["p_segment"]))
    hb, hs = holm_adjust([r[1] for r in rows]), holm_adjust([r[2] for r in rows])
    return {r[0]: (hb[i], hs[i]) for i, r in enumerate(rows)}, len(rows)


