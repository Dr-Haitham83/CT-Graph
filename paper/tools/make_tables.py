            rt = (f3(reps[0]) if len(reps) == 1 else f"{min(reps):.3f}--{max(reps):.3f} ({len(reps)})") if reps else "--"
            lines.append(f"\\quad {label} & {r} & {sc['val']:.3f} & {sc['calibration']:.3f} & \\textbf{{{sc['test']:.3f}}} & {rt} \\\\")
