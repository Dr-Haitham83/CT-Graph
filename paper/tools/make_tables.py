STRICT_MODES = (("none", "None (context branch)"), ("seg", "Per segment"), ("merged", "Merged timeline"))


def strict(key, mode, run="strict404"):
    """Strict ablation result; run 'strict404' (runner, primary) or 'strict' (repeat on a second account, same data)."""
    path = REV / run / f"{key}-strict{mode}" / "strict" / "strict.json"
    return json.loads(path.read_text()) if path.exists() else None


def strict_repeats(key, mode):
    """Test scores of the repeat runs of a strict configuration: the same-seed rerun on a second account and,
    per segment, three further seed sets (45-47, 48-50, 51-53)."""
    out = []
    r_ = strict(key, mode, "strict")
    if r_:
        out.append(r_["test_by_val_cvar"])
    if mode == "seg":
        for rp in ("r2", "r3", "r4"):
            f_ = sorted((REV / "strictrep" / f"{key}-{rp}").glob("**/strict.json"))
            if f_:
                out.append(json.loads(f_[0].read_text())["test_by_val_cvar"])
    return out


def ctg_repeat(key):
    """CT-Graph CPU re-run (frozen checkpoints re-evaluated on CPU, fused anew): (macro-MCC, selected rule)."""
    f_ = sorted((REV / "gpost" / f"5gs-{key}-cpuref").glob("**/posthoc.json"))
    if not f_:
        return None
    d = json.loads(f_[0].read_text())
    return d["all_metrics"]["ct_graph_hybrid"]["macro_mcc"], d["hybrid_primary"]["rule"]


