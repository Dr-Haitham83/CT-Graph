def f3(v):
    if v is None:
        return "--"
    return f"$-${abs(v):.3f}" if round(v, 3) < 0 else f"{abs(v) if round(v, 3) == 0 else v:.3f}"


def fp(p):
    return "$<$0.001" if p < 0.001 else f"{p:.3f}"


def signed(v, d=3):
    if round(v, d) == 0:
        return f"${0:.{d}f}$"
    return f"${'+' if v >= 0 else '-'}{abs(v):.{d}f}$"


def sg(v, d=3):
    """Signed value for running text (true minus sign, no sign on a rounded zero)."""
    if round(v, d) == 0:
        return f"{0:.{d}f}"
    return f"{'+' if v >= 0 else '$-$'}{abs(v):.{d}f}"


def write(name, body):
    OUT.mkdir(exist_ok=True)
    (OUT / f"{name}.tex").write_text("% generated by paper/tools/make_tables.py -- do not edit\n" + body + "\n")
    print(f"tables/{name}.tex")


def tab(spec, head, lines, colsep=None):
    """Table body set to the full text width: tabular* whose column gaps stretch to fill the line."""
    pre = f"\\setlength{{\\tabcolsep}}{{{colsep}}}\n" if colsep else ""
    return (pre + "\\begin{tabular*}{\\textwidth}{@{\\extracolsep{\\fill}}" + spec + "@{}}\n\\toprule\n" + head
            + " \\\\\n\\midrule\n" + "\n".join(lines) + "\n\\bottomrule\n\\end{tabular*}")


def group(title, ncols):
    """Italic heading row of a group of indented rows."""
    return f"\\multicolumn{{{ncols}}}{{@{{}}l}}{{\\emph{{{title}}}}} \\\\"


