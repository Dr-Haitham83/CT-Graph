def ev_tree_runs(key, t):
    """Test scores of the strict LightGBM + rel. under attack t ('ref' = no attack): every available seed set."""
    if t == "ref":
        d = strict(key, "seg")
        return ([d["scores"][d["selected"]["by_val_cvar"]]["test"]] if d else []) + strict_repeats(key, "seg")
    out = []
    path = REV / "strictev" / f"{key}-strict{t}" / "strict" / "strict.json"
    if path.exists():
        out.append(json.loads(path.read_text())["test_by_val_cvar"])
    for rp in ("r2", "r3"):
        f_ = sorted((REV / "strictevrep" / f"5gs-{key}-strict{t}{rp}").glob("**/strict.json"))
        if f_:
            out.append(json.loads(f_[0].read_text())["test_by_val_cvar"])
    return out


