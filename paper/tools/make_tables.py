    resc_ = lambda t, sd: sorted((REV / "cpu" / f"cic-cpu{t}s{sd}").glob("*/evaluations/*/results.json"))  # noqa: E731
    sc_ = [sd for sd in (42, 43, 44) if resc_("ref", sd) and resc_("nomem7d", sd)]
    if sc_:
        for t in ("ref", "nomem7d"):
            v[f"mem-cic-{t}"] = f3(_st.mean(json.loads(resc_(t, sd)[0].read_text())["test"]["macro_mcc"] for sd in sc_))
        v["mem-cic-n"] = str(len(sc_))
    for t in ("ref", "merge", "g60", "g300"):
        f_ = sorted((REV / "gpost" / f"cic-cpu{t}").glob("**/posthoc.json"))
        if f_:
            am = json.loads(f_[0].read_text())["all_metrics"]
            for m_, tag in (("ct_graph_hybrid", "hyb"), ("graph_ensemble", "gr"), ("context_branch", "ctx")):
                v[f"tp-cic-{t}-{tag}"] = f3(am[m_]["macro_mcc"])
    for t in ("ref", "merge", "g30", "g121"):
        f_ = sorted((REV / "gpost" / f"ton-cpu{t}").glob("**/posthoc.json"))
        if f_:
            am = json.loads(f_[0].read_text())["all_metrics"]
            for m_, tag in (("ct_graph_hybrid", "hyb"), ("graph_ensemble", "gr"), ("context_branch", "ctx")):
                v[f"tp-ton-{t}-{tag}"] = f3(am[m_]["macro_mcc"])
            hy = json.loads(f_[0].read_text())["hybrid"]
            v[f"tp-ton-{t}-cvarw"] = f3(hy["test"]["ct_graph_hybrid_global"]["macro_mcc"])
            v[f"tp-ton-{t}-cvarwg"] = f"{hy['weight_graph']:.1f}"
    for key in ("ton", "cic", "bs1", "bs2"):
        r_ = rev(key, "rev2")
        if r_ and "calibration_binary" in r_:
            for m_, tag in (("ct_graph_hybrid", "hyb"), ("LightGBM_rel", "lgbmrel"), ("XGBoost_rel", "xgbrel"), ("LightGBM", "lgbm")):
                c_ = r_["calibration_binary"].get(m_)
                if c_:
                    v[f"cal-{key}-{tag}-brier"], v[f"cal-{key}-{tag}-ece"] = f"{c_['brier']:.3f}", f"{c_['ece_15']:.3f}"
        if r_ and "target_benign_recalibration" in r_:
            for m_, tag in (("ct_graph_hybrid", "hyb"), ("LightGBM_rel", "lgbmrel")):
                tc_ = r_["target_benign_recalibration"].get(m_, {})
                for k_, short in (("random_benign_0.01_far_0.001", "r1"), ("earliest_benign_0.05_far_0.001", "e5"),
                                  ("earliest_benign_0.01_far_0.001", "e1")):
                    if k_ in tc_:
                        v[f"rc-{key}-{tag}-{short}-far"] = f"{100 * tc_[k_]['test_far']:.2f}"
                        v[f"rc-{key}-{tag}-{short}-dr"] = f"{100 * tc_[k_]['test_detection_rate']:.1f}"
                        v[f"rc-{key}-{short}-n"] = f"{tc_[k_]['benign_sample']:,}"
        if r_ and "em_prior_adjustment" in r_:
            v[f"em-{key}-far"] = f"{100 * r_['em_prior_adjustment']['ct_graph_hybrid']['test_far']:.0f}"
    pc = perflow_counts()
    v.update({"flow-cols-nf": str(pc["nf"]["columns"]), "flow-cols-5g": str(pc["5g"]["columns"]),
              "flow-release-nf": str(pc["nf"]["release"]), "flow-release-5g": str(pc["5g"]["release"]),
              "flow-empty": WORDS[pc["nf"]["empty"]].lower()})
    # abstract: every gain is significant in three settings; in BS2->BS1 only those over the DNN and NEGSC are
    sig = [k for k, *_ in E.SETTINGS if k != "bs2"]
    holm = [mult[(k, b)]["holm_block"] for k in sig for b in E.BASELINES]
    assert max(holm) < 0.05 and all(E.binary_comparison(k)["p_block"] < 0.05 for k in sig)
    assert all(mult[("bs2", b)]["holm_block"] < 0.05 for b in ("DNN", "NEGSC"))
    assert all(mult[("bs2", b)]["holm_block"] >= 0.05 for b in ("LightGBM", "XGBoost")) and E.binary_comparison("bs2")["p_block"] >= 0.05
    v["holm-sig-max"] = fp(max(holm)).replace("$<$", "<")
    # abstract: margin over the strongest multi-class baseline of each setting, and the per-flow accuracy ceilings
    gains = [E.metric(k, "ct_graph_hybrid", "macro_mcc") - max(E.metric(k, b, "macro_mcc") for b in E.BASELINES) for k, *_ in E.SETTINGS]
    assert min(gains) > 0
    v["gain-best-min"], v["gain-best-max"] = f"{min(gains):.3f}", f"{max(gains):.3f}"
    ceilings = [E.audit(k)["ceiling"] for k, *_ in E.SETTINGS]
    v["audit-ceiling-min"], v["audit-ceiling-max"] = f"{100 * min(ceilings):.1f}", f"{100 * max(ceilings):.1f}"
    v["bs2-holm-gbdt"] = fp(min(mult[("bs2", b)]["holm_block"] for b in ("LightGBM", "XGBoost"))).replace("$<$", "<")
    fails = E.flat_failures()
    v.update({"fail-n": str(len(fails)), "fail-n-word": WORDS[len(fails)], "fail-n-lower": WORDS[len(fails)].lower(),
              "fail-best-max": f"{max(max(r['baselines'].values()) for r in fails):.2f}",
              "fail-ctg-min": f"{min(r['ctgraph'] for r in fails):.2f}", "fail-ctg-max": f"{max(r['ctgraph'] for r in fails):.2f}"})
    lines = ["% generated by paper/tools/make_tables.py -- do not edit"]
    lines += [f"\\expandafter\\def\\csname ctgv{k}\\endcsname{{{val}}}" for k, val in sorted(v.items())]
    (OUT / "numbers.tex").write_text("\n".join(lines) + "\n")
    print(f"tables/numbers.tex ({len(v)} values)")


